def render(text, scale=1, spacing=1):
    """1-bit mask of the text, every font pixel drawn as a scale x scale block."""
    text = text.upper()
    width = sum(len(GLYPHS[c][0]) + spacing for c in text) - spacing
    mask = Image.new("1", (width * scale, 7 * scale), 0)
    x = 0
    for c in text:
        rows = GLYPHS[c]
        for y, row in enumerate(rows):
            for dx, bit in enumerate(row):
                if bit == "1":
                    mask.paste(1, (( x + dx) * scale, y * scale, (x + dx + 1) * scale, (y + 1) * scale))
        x += len(rows[0]) + spacing
    return mask
